#!/usr/bin/env python3
"""Generate test/host/vectors.h from the Python reference tech/iot/app/protocol.py.

Run from anywhere:  python3 firmware/knee_pod_s3/test/host/gen_vectors.py
The C host test compares its packet bytes and pairing counters with these
values, so the firmware stays byte-compatible with the Python reference.
"""
import importlib.util
import pathlib
import struct
import sys

REPO = pathlib.Path(__file__).resolve().parents[4]
spec = importlib.util.spec_from_file_location("protocol", REPO / "tech/iot/app/protocol.py")
proto = importlib.util.module_from_spec(spec)
spec.loader.exec_module(proto)

G = 9.80665
ACCEL_LSB = 8192.0
GYRO_LSB = 65.5
SESSION = bytes([0x10, 0x21, 0x32, 0x43, 0x54, 0x65, 0x76, 0x87])
OTHER = bytes([0xAA] * 8)
PEER = b"\x02\x11\x22\x33\x44\x55"
WRONG = b"\x02\x99\x99\x99\x99\x99"


def f32_bits(x):
    return struct.unpack("<I", struct.pack("<f", x))[0]


def counts_to_si(counts):
    """Shank counts -> float32 SI values exactly as the shank would send them."""
    out = []
    for i, c in enumerate(counts):
        if i < 3:
            out.append(c * G / ACCEL_LSB)
        else:
            out.append(c / GYRO_LSB * 3.14159265358979323846 / 180.0)
    return [struct.unpack("<f", struct.pack("<f", v))[0] for v in out]


def hexbytes(b):
    return ", ".join(f"0x{x:02x}" for x in b)


# Scenario (times in ms). Each step: ("tick", t_ms, seq) or ("rx", t_ms, sender, data).
THIGH = [1000, -2000, 8192, 10, -20, 30]
SHANK_COUNTS = [1000, -2000, 8192, 300, -65, 655]
SHANK_BITS = [f32_bits(v) for v in counts_to_si(SHANK_COUNTS)]


def resp(seq, session=SESSION):
    vals = [struct.unpack("<f", struct.pack("<I", b))[0] for b in SHANK_BITS]
    return proto.response(session, seq, seq * 20, vals)


STEPS = [
    ("tick", 0, 0),
    ("rx", 5, PEER, resp(0)),
    ("tick", 20, 1),
    ("tick", 40, 2),             # seq 1 expires here (timeout)
    ("rx", 45, PEER, resp(1)),   # late/unmatched for seq 1
    ("rx", 50, PEER, resp(2)),   # paired
    ("tick", 60, 3),
    ("rx", 80, PEER, resp(3)),   # late: unmatched
    ("tick", 100, 4),            # seq 3 expires here (timeout)
    ("rx", 103, WRONG, resp(4)),
    ("rx", 104, PEER, b"\x01\x02\x03"),
    ("rx", 106, PEER, resp(4, OTHER)),
    ("rx", 110, PEER, resp(4)),  # paired
]


def run_python_pairer():
    p = proto.Pairer(PEER, SESSION, deadline_ms=15)
    rows = []
    for step in STEPS:
        if step[0] == "tick":
            _, t, seq = step
            if p.pending is not None:
                if p.expire(t):
                    rows.append(("loss",))
            p.begin(seq, t, seq * 20, [0.0] * 6)
        else:
            _, t, sender, data = step
            r = p.accept(sender, data, t)
            if r is not None:
                rows.append(("paired", r[0]))
    return p.counts, rows


def run_python_gate():
    g = proto.RequestGate(PEER)
    req = lambda seq, session=SESSION: proto.request(session, seq, seq * 20)
    g.accept(PEER, req(5))
    g.accept(PEER, req(5))           # replay
    g.accept(PEER, req(6, OTHER))    # stale session
    g.accept(WRONG, req(7))          # wrong sender
    g.accept(PEER, b"\x01\x02")      # invalid length
    g.accept(PEER, resp(9))          # wrong kind
    g.accept(PEER, req(7))           # accepted
    return g.counts


def main():
    counts, _rows = run_python_pairer()  # counts is a dict
    gate = run_python_gate()
    out = []
    w = out.append
    w("/* GENERATED by test/host/gen_vectors.py from tech/iot/app/protocol.py. Do not edit. */")
    w("#ifndef POD_VECTORS_H")
    w("#define POD_VECTORS_H")
    w("#include <stdint.h>")
    w("static const uint8_t V_SESSION[8] = {%s};" % hexbytes(SESSION))
    w("static const uint8_t V_REQ_SEQ5[18] = {%s};" % hexbytes(proto.request(SESSION, 5, 100)))
    w("static const uint8_t V_RESP_SEQ7[42] = {%s};" % hexbytes(resp(7)))
    w("static const uint32_t V_SHANK_BITS[6] = {%s};" % ", ".join(f"0x{b:08x}u" for b in SHANK_BITS))
    w("static const int16_t V_SHANK_COUNTS[6] = {%s};" % ", ".join(str(c) for c in SHANK_COUNTS))
    w("static const int16_t V_THIGH_COUNTS[6] = {%s};" % ", ".join(str(c) for c in THIGH))
    w("static const uint8_t V_PEER_FILLER[1] = {0};")
    # Python reference counters for the scenario (C test checks these exactly).
    for k in ["paired", "timeout", "wrong_sender", "invalid", "stale_session", "unmatched"]:
        w(f"#define PY_PAIR_{k.upper()} {counts[k]}")
    for k in ["accepted", "wrong_sender", "invalid", "stale_session", "replay"]:
        w(f"#define PY_GATE_{k.upper()} {gate[k]}")
    w("#endif")
    path = pathlib.Path(__file__).with_name("vectors.h")
    path.write_text("\n".join(out) + "\n")
    print("wrote", path)
    print("pairer counts:", counts)
    print("gate counts:", gate)


if __name__ == "__main__":
    sys.exit(main())
